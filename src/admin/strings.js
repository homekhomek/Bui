// a('key', { n: 3 }): same {placeholder} substitution as t(); symbol
// placeholders ({charge}) are left in place for SymbolText-style rendering.
export function a(key, vars = {}) {
  return (STRINGS[key] ?? key).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}
